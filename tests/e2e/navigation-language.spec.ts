import { test, expect } from '@playwright/test';

test('contextual controls, persistent English, and timer-safe preferences', async ({ page, context }) => {
  test.setTimeout(90000);
  await context.grantPermissions(['notifications']);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('button', { name: '开始专注', exact: true })).toBeEnabled();
  const state = () => page.evaluate(() => JSON.parse(localStorage.getItem('pomodoro.guest.v1') || '{}').state);
  const noChinese = async () => expect(await page.locator('body').innerText()).not.toMatch(/\p{Script=Han}/u);
  const dismiss = async (language: 'zh' | 'en') => {
    await page.getByLabel(language === 'zh' ? '关闭面板' : 'Dismiss panel', { exact: true }).click({ position: { x: 4, y: 4 } });
    await page.waitForTimeout(600);
  };
  await expect(page.getByRole('button', { name: '打开设置', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: '设置', exact: true }).click();
  await page.getByRole('button', { name: '番茄钟设置', exact: true }).click();
  await expect(page.getByRole('switch', { name: '专注计时通知', exact: true })).toBeVisible();
  await expect(page.getByText('实时通知与胶囊', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: '增加短休息', exact: true }).click();
  await page.getByLabel('自定义分钟数', { exact: true }).fill('43');
  await page.getByRole('button', { name: '设定时长', exact: true }).click();
  await expect(page.getByTestId('timer-digits')).toHaveText('43:00');
  const id = (await state()).timer.id;
  expect((await state()).settings.breakMinutes).toBe(6);
  await page.getByRole('button', { name: '切换深色模式', exact: true }).click();
  await page.getByRole('button', { name: '切换浅色模式', exact: true }).click();
  expect((await state()).timer.id).toBe(id);
  await page.getByRole('tab', { name: '统计', exact: true }).click();
  await page.getByRole('button', { name: '设置统计目标', exact: true }).click();
  await page.getByRole('button', { name: '增加每日目标', exact: true }).click();
  expect((await state()).settings.dailyGoal).toBe(135);
  expect((await state()).timer.id).toBe(id);
  await dismiss('zh');
  await page.getByRole('button', { name: '设置', exact: true }).click();
  await page.getByRole('button', { name: '语言：简体中文', exact: true }).click();
  await page.getByRole('menuitem', { name: 'English', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Language: English', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Cloud sync', exact: true }).click();
  await page.getByRole('tab', { name: 'Sign up', exact: true }).click();
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await expect(page.getByText('Enter a valid email address', { exact: true })).toBeVisible();
  await noChinese();
  await dismiss('en');
  await page.getByRole('button', { name: 'Set daily goal', exact: true }).click();
  await page.getByRole('button', { name: 'Increase Daily goal', exact: true }).click();
  expect((await state()).settings.dailyGoal).toBe(150);
  expect((await state()).timer.id).toBe(id);
  await noChinese();
  await dismiss('en');
  await page.getByRole('tab', { name: 'Month', exact: true }).click();
  await noChinese();
  await page.screenshot({ path: 'screenshots/v105-statistics-en.png' });
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export records', exact: true }).click();
  const file = await download;
  const stream = await file.createReadStream();
  const chunks: Buffer[] = [];
  for await (const chunk of stream!) chunks.push(Buffer.from(chunk));
  expect(Buffer.concat(chunks).toString('utf8')).toContain('Active focus seconds');
  await page.getByRole('tab', { name: 'Timer', exact: true }).click();
  await page.getByRole('tab', { name: 'Count up', exact: true }).click();
  await page.getByRole('button', { name: 'Start focus', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Pause', exact: true })).toBeVisible();
  const runningId = (await state()).timer.id;
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'Timer settings', exact: true }).click();
  await expect(page.getByLabel('Focus minutes', { exact: true })).toBeVisible();
  await dismiss('en');
  expect((await state()).timer.id).toBe(runningId);
  expect((await state()).timer.status).toBe('running');
  await page.getByRole('button', { name: 'End session', exact: true }).click();
  await noChinese();
  await page.getByRole('button', { name: 'End without saving', exact: true }).click();
  await page.getByRole('tab', { name: 'Countdown', exact: true }).click();
  await expect(page.getByTestId('timer-digits')).toHaveText('43:00');
  await page.getByRole('button', { name: 'Switch to dark mode', exact: true }).click();
  await page.screenshot({ path: 'screenshots/v105-timer-en-dark.png' });
  await page.reload();
  await expect(page.getByTestId('timer-digits')).toHaveText('43:00');
  await expect(page.getByRole('button', { name: 'Switch to light mode', exact: true })).toBeVisible();
  await noChinese();
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'Language: English', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Simplified Chinese', exact: true }).click();
  await expect(page.getByRole('button', { name: '语言：简体中文', exact: true })).toBeVisible();
  expect((await state()).settings.focusMinutes).toBe(43);
  expect((await state()).settings.dailyGoal).toBe(150);
  expect(errors).toEqual([]);
});
